#include "ft_printf.h"

void	ft_hex_x(unsigned long n, int *sum)
{
	char	*base;

	base = "0123456789abcdef";
	if (n > 15)
	{
		ft_hex_x(n / 16, sum);
	}
	write(1, &base[n % 16], 1);
	(*sum)++;
}
