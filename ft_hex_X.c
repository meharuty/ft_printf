#include "ft_printf.h"

void	ft_hex_xx(unsigned long n, int *sum)
{
	char	*base;

	base = "0123456789ABCDEF";
	if (n > 15)
	{
		ft_hex_xx(n / 16, sum);
	}
	write(1, &base[n % 16], 1);
	(*sum)++;
}
