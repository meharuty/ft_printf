#include "ft_printf.h"

void	ft_putnbr_id(int n, int *sum)
{
	char	c;

	if (n == -2147483648)
	{
		write(1, "-2147483648", 11);
		(*sum) += 11;
		return ;
	}
	if (n < 0)
	{
		write (1, "-", 1);
		(*sum)++;
		n = -n;
	}
	if (n > 9)
		ft_putnbr_id(n / 10, sum);
	c = (n % 10) + '0';
	write (1, &c, 1);
	(*sum)++;
}
